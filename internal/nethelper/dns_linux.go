//go:build linux

package nethelper

import (
	"context"
	"fmt"
	"net"
	"os"
	"os/exec"
	"strings"
	"time"
)

// The on-link peer from cmd/xrayhelper/route.go. The TUN's port 53 rule
// delivers both UDP and TCP queries for this address to Xray's DNS outbound.
const xrayDNS = "198.18.0.2"

func resolverAddresses(conf string) []string {
	var servers []string
	for _, line := range strings.Split(conf, "\n") {
		fields := strings.Fields(line)
		if len(fields) >= 2 && fields[0] == "nameserver" {
			servers = append(servers, fields[1])
		}
	}
	return servers
}

func resolvedStub(servers []string) bool {
	for _, server := range servers {
		if server != "127.0.0.53" && server != "127.0.0.54" {
			return false
		}
	}
	return len(servers) > 0
}

func setXrayDNS(iface string) error {
	conf, err := os.ReadFile("/etc/resolv.conf")
	if err != nil {
		return err
	}
	stub := resolvedStub(resolverAddresses(string(conf)))
	nm := strings.Contains(string(conf), "# Generated by NetworkManager")
	if !stub && !nm {
		return fmt.Errorf("cannot configure tunnel DNS: /etc/resolv.conf must use NetworkManager or the systemd-resolved stub")
	}

	ctx, cancel := context.WithTimeout(context.Background(), 12*time.Second)
	defer cancel()
	run := func(name string, args ...string) error {
		output, err := exec.CommandContext(ctx, name, args...).CombinedOutput()
		if err != nil {
			return fmt.Errorf("%s: %w: %s", name, err, strings.TrimSpace(string(output)))
		}
		return nil
	}
	// Xray creates and addresses the device asynchronously. NetworkManager
	// also needs time to adopt the external connection before device modify.
	if err := waitDNS(ctx, func() error {
		link, err := net.InterfaceByName(iface)
		if err != nil {
			return err
		}
		addrs, err := link.Addrs()
		if err != nil {
			return err
		}
		for _, addr := range addrs {
			if addr.String() == "198.18.0.1/15" {
				return nil
			}
		}
		return fmt.Errorf("waiting for the tunnel address on %s", iface)
	}); err != nil {
		return err
	}
	if !stub {
		if err := setNetworkManagerDNS(ctx, iface, "/etc/resolv.conf", run); err != nil {
			return err
		}
	}
	if stub || resolvedRunning() {
		if err := waitDNS(ctx, func() error { return run("resolvectl", "dns", iface, xrayDNS) }); err != nil {
			return err
		}
		return run("resolvectl", "domain", iface, "~.")
	}
	return nil
}

func setNetworkManagerDNS(ctx context.Context, iface, confPath string, run func(string, ...string) error) error {
	// A negative priority excludes DNS from other connections. Device modify
	// changes only the live TUN connection and expires when Xray closes it.
	if err := waitDNS(ctx, func() error {
		return run("nmcli", "device", "modify", iface,
			"ipv4.dns", xrayDNS, "ipv4.dns-search", "~.", "ipv4.dns-priority", "-2147483648")
	}); err != nil {
		return err
	}
	return waitDNS(ctx, func() error {
		current, err := os.ReadFile(confPath)
		if err != nil {
			return err
		}
		servers := resolverAddresses(string(current))
		if len(servers) != 1 || servers[0] != xrayDNS {
			return fmt.Errorf("NetworkManager has not published the tunnel as the only DNS server")
		}
		return nil
	})
}

func waitDNS(ctx context.Context, check func() error) error {
	for {
		err := check()
		if err == nil {
			return nil
		}
		select {
		case <-ctx.Done():
			return fmt.Errorf("configure tunnel DNS: %w", err)
		case <-time.After(200 * time.Millisecond):
		}
	}
}

func resolvedRunning() bool {
	_, err := os.Stat("/run/systemd/resolve/io.systemd.Resolve")
	return err == nil
}
