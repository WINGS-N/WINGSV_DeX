package nethelper

import (
	"context"
	"os"
	"path/filepath"
	"slices"
	"testing"
)

func TestNetworkManagerDNSExcludesUplink(t *testing.T) {
	for _, extra := range []string{"", "nameserver 192.168.1.1\n"} {
		conf := filepath.Join(t.TempDir(), "resolv.conf")
		ctx, cancel := context.WithCancel(context.Background())
		err := setNetworkManagerDNS(ctx, "wingsv-tun", conf, func(name string, args ...string) error {
			want := []string{"device", "modify", "wingsv-tun", "ipv4.dns", xrayDNS, "ipv4.dns-search", "~.", "ipv4.dns-priority", "-2147483648"}
			if name != "nmcli" || !slices.Equal(args, want) {
				t.Fatalf("unexpected command: %s %v", name, args)
			}
			cancel()
			return os.WriteFile(conf, []byte("# Generated by NetworkManager\nnameserver "+xrayDNS+"\n"+extra), 0600)
		})
		cancel()
		if (err == nil) != (extra == "") {
			t.Errorf("upstream %q: %v", extra, err)
		}
	}
}
